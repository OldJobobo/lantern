test("paper overlay is outside CRT effects with window-level modal routing", () => {
  const overlayAt = panel.lastIndexOf("MapOverlay {")
  const terminalAt = panel.indexOf("id: terminalShell")
  const shaderAt = panel.indexOf("id: crtSource")
  const dragAt = panel.indexOf("id: topDragHandle")
  assert.ok(overlayAt > terminalAt)
  assert.ok(overlayAt > shaderAt, "overlay must be declared after the bezel's CRT source closes")
  assert.ok(dragAt > overlayAt, "window drag strip must stack after the map")
  assert.match(panel.slice(overlayAt), /crtRect: Qt\.rect\(46, 60, 928, 617\)/)
  assert.match(panel.slice(overlayAt), /dragStripHeight: 42/)
  assert.match(panel.slice(dragAt), /z: 120/)
  assert.match(panel, /Shortcut \{[\s\S]*sequence: "Ctrl\+P"[\s\S]*autoRepeat: false[\s\S]*enabled: root\.viewMode === "game" && mapOverlay\.motionState === "closed"/)
  assert.match(panel, /if \(mapOverlay\.modal\) mapOverlay\.focusCurrent\(\)/)
  assert.match(panel, /enabled: gameProc\.running && root\.fileActionMode === "" && !root\.mapModal\(\)/)
})

test("map availability, reset, forced closure, and reduced motion are host-owned", () => {
  assert.match(panel, /readonly property bool mapAvailable:[\s\S]*currentCartridge\.engine === "zmachine"[\s\S]*mapObserverReady && !mapObserverSuppressed/)
  assert.match(panel, /!mapObserverReady \? "WAITING FOR THE FIRST CONFIRMED ROOM"/)
  assert.match(panel, /model: \[\{ label: root\.mapAvailable \? "MAP  \^P" : "MAP  --", action: "map" \}/)
  assert.match(panel, /onResetMapRequested: root\.resetMapMemory\(\)/)
  const resetFunction = panel.slice(panel.indexOf("function resetMapMemory()"), panel.indexOf("function enqueueMapPersistenceWrite()"))
  assert.match(resetFunction, /op: "reset"/)
  assert.ok(resetFunction.indexOf("if (!result.accepted)") < resetFunction.indexOf("mapState = Automap.createEmptyState(identity)"))
  assert.match(resetFunction, /MAP RESET DEFERRED — TRY AGAIN/)
  assert.match(panel, /modelData\.action === "map" \? root\.mapAvailable/)
  assert.ok((panel.match(/forceMapClosed\(\)/g) || []).length >= 8)
  assert.match(panel, /var accessibility = config\.accessibility \|\| \{\}/)
  assert.match(panel, /reduceMotion = accessibility\.reduce_motion/)
  assert.match(config, /\[accessibility\][\s\S]*reduce_motion = false/)
})

test("full persistence queue retains final map state until its tail write is admitted", () => {
  const clear = panel.slice(panel.indexOf("function clearMapSession(persistFinal)"), panel.indexOf("function beginMapStartup()"))
  assert.match(panel, /property bool mapFinalizationPending: false/)
  assert.match(clear, /persistFinal === true && mapCartridgeSupported && !enqueueMapPersistenceWrite\(\)/)
  assert.ok(clear.indexOf("mapFinalizationPending = true") < clear.indexOf("return false"))
  assert.ok(clear.indexOf("return false") < clear.indexOf("finishMapSessionClear()"))
  assert.doesNotMatch(clear, /mapFingerprint = ""|mapState = Automap\.createEmptyState/)

  const completion = panel.slice(panel.indexOf("id: mapPersistenceProc"), panel.indexOf("id: mapWriteDebounce"))
  assert.ok(completion.indexOf("root.startNextMapPersistenceOperation()") <
    completion.indexOf("root.retryPendingMapFinalization()"))
  assert.match(panel, /function retryPendingMapFinalization\(\)[\s\S]*enqueueMapPersistenceWrite\(\)[\s\S]*finishMapSessionClear\(\)/)
  assert.match(panel, /if \(mapFinalizationPending\)[\s\S]*FINISHING MAP CHECKPOINT — TRY AGAIN[\s\S]*return/)
})

