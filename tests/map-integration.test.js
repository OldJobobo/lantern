const test = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")

const root = path.resolve(__dirname, "..")
const panel = fs.readFileSync(path.join(root, "Panel.qml"), "utf8")
const config = fs.readFileSync(path.join(root, "lantern.toml"), "utf8")
const docs = fs.readFileSync(path.join(root, "docs/map-state-helper.md"), "utf8")

test("Panel observes raw Frotz lines before presentation cleanup", () => {
  assert.match(panel, /import "Automap\.js" as Automap/)
  assert.match(panel, /import "AutomapSession\.js" as AutomapSession/)
  const stdout = panel.slice(panel.indexOf("id: gameProc"), panel.indexOf("stderr: StdioCollector", panel.indexOf("id: gameProc")))
  assert.ok(stdout.indexOf("root.observeAutomapOutput(line)") < stdout.indexOf("root.appendOutput(Automap.stripRoomMetadata(line))"))
  assert.doesNotMatch(stdout, /Model\.cleanOutput/)
  assert.match(panel, /Automap\.parseRoomEvent\(raw\)/)
  assert.match(panel, /Automap\.parseInputEvent\(raw\)/)
  assert.match(panel, /Automap\.pairRoomStatus\(pending, raw\)/)
  assert.match(panel, /Automap\.reduceIdentifiedTurn\(mapState, command, observation\)/)
  assert.doesNotMatch(panel, /Automap\.reduceTurn\(/)
  assert.match(stdout, /environment:.*LANTERN_ROOM_EVENTS.*mapCartridgeSupported \? "1" : "0"/)
})

